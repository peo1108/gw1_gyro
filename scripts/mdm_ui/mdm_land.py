"""Two-column home / "Thêm" pages for wide screens (landscape tablet, landscape phone).

m32 turned both pages into one vertical column for phones. On a landscape tablet (~1300dp wide)
that single column is stretched edge to edge and every card looks huge. Screens at least 720dp
wide now get res/layout-w720dp-v13/ copies laid out in two columns; portrait phones keep the
one-column res/layout/ version untouched.

  home   : left  = hero (logo, Gyro / Kích hoạt tiles) + device info
           right = "Trò chơi" header, notices, game list
  Thêm   : left  = first column (hero, support, backup, reset)
           right = second column (Module Gyro, settings groups)

The left column is @dimen/mdm_side_w wide, the right one takes the rest after @dimen/mdm_col_gap.
Only containers are added or re-oriented: every id, tag and custom view stays, because
MainPageView / SettingsPageView look them up at runtime (checked after writing).

Re-run after editing res/layout/main_page_view.xml or settings_page_view.xml.

usage: python mdm_land.py <build_dir>
"""
import os
import re
import sys
from xml.dom import minidom

B = sys.argv[1]
SRC = os.path.join(B, "res", "layout")
OUT = os.path.join(B, "res", "layout-w720dp-v13")
MARK = " generated by scripts/mdm_ui/mdm_land.py - edit res/layout/ and re-run "


def E(n):
    return [c for c in n.childNodes if c.nodeType == 1]


def scroll_body(doc):
    sv = doc.getElementsByTagName("ScrollView")[0]
    return E(sv)[0]


def ids(text):
    return sorted(re.findall(r'android:(?:id|tag)="([^"]+)"', text))


def home(doc):
    body = scroll_body(doc)
    kids = E(body)
    left, rest = kids[0], kids[1:]
    row = doc.createElement("LinearLayout")
    for k, v in (("android:orientation", "horizontal"), ("android:baselineAligned", "false"),
                 ("android:layout_width", "fill_parent"), ("android:layout_height", "wrap_content")):
        row.setAttribute(k, v)
    right = doc.createElement("LinearLayout")
    for k, v in (("android:orientation", "vertical"), ("android:layout_width", "0.0dip"),
                 ("android:layout_height", "wrap_content"), ("android:layout_weight", "1.0"),
                 ("android:layout_marginStart", "@dimen/mdm_col_gap")):
        right.setAttribute(k, v)
    left.setAttribute("android:layout_width", "@dimen/mdm_side_w")
    for k in rest:
        body.removeChild(k)
        right.appendChild(k)
    body.removeChild(left)
    row.appendChild(left)
    row.appendChild(right)
    body.appendChild(row)


def settings(doc):
    body = scroll_body(doc)
    col1, col2 = E(body)[:2]
    body.setAttribute("android:orientation", "horizontal")
    body.setAttribute("android:baselineAligned", "false")
    col1.setAttribute("android:layout_width", "@dimen/mdm_side_w")
    col2.setAttribute("android:layout_width", "0.0dip")
    col2.setAttribute("android:layout_weight", "1.0")
    col2.setAttribute("android:layout_marginStart", "@dimen/mdm_col_gap")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, fn in (("main_page_view", home), ("settings_page_view", settings)):
        src_path = os.path.join(SRC, name + ".xml")
        with open(src_path, encoding="utf-8") as f:
            src = f.read()
        doc = minidom.parseString(src.encode("utf-8"))
        fn(doc)
        doc.insertBefore(doc.createComment(MARK), doc.documentElement)
        out = doc.toxml(encoding="utf-8").decode("utf-8")
        if ids(out) != ids(src):
            sys.exit("id/tag set changed in " + name)
        with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print("wrote res/layout-w720dp-v13/%s.xml" % name)


main()
