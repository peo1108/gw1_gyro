"""Tablet-sized copies of the in-game overlay menus.

On a tablet the overlay menus (PUBG quick panel, keymap picker/editor, "Cài đặt AI" settings) are
drawn with phone-sized dips and look tiny. Phones must stay exactly as they are, so nothing in
res/layout/ is touched: this writes scaled copies to res/layout-sw600dp-v13/, which Android only
picks when the smallest screen width is >= 600dp.

For every layout in the set:
  * each dip/dp/sp value is multiplied by SCALE (literal values and @dimen/ references, which are
    resolved to their real value first - values-sw600dp-v13 wins over values/);
  * text widgets that rely on the default 14sp (no textSize, no resolvable style size) get
    14sp * SCALE so the text grows with its box;
  * ids, tags, classes and view order are untouched (checked after writing).

The set = SEEDS + closure over <include>, layouts inflated by the custom view classes used in a
layout (incl. inner classes), and every overlay layout that uses one of the shared WIDGETS (so the
tabs of one settings window keep one size). EXCLUDE and Activity layouts are never scaled.

Re-run after editing any of these layouts in res/layout/: generated files carry MARK and are
deleted and rebuilt on every run.

usage: python mdm_tablet.py <build_dir> [--list]
"""
import glob
import os
import re
import sys

SCALE = 1.3
OUT_DIR = "layout-sw600dp-v13"
MARK = "<!-- generated by scripts/mdm_ui/mdm_tablet.py - edit res/layout/ and re-run -->"

SEEDS = [
    # PUBG quick panel
    "pubg_panel", "pubg_map_panel_view", "pubg_adjust_rc_value_panel_view",
    "pubg_adjust_dynamic_rc_value_view", "pubg_adjust_coefficient_view",
    "pubg_adjust_rc_value_base_view", "pubg_adjust_rc_value_component_settings_view",
    # same quick-adjust frame for the other games, its body is scaled through the widgets
    "gnyx_adjust_rc_value_panel_view", "general_rc_adjust_rc_value_panel_view",
    # keymap picker + editor
    "select_keymap_container_view", "select_keymap_table_row", "keymap_upload_floating_panel",
    # "Cài đặt AI" and the settings window that hosts it
    "user_settings_view", "pubg_extension_settings_view",
]
# classes whose inflated layouts are seeds too (keymap editor: per-key settings + macro editor)
SEED_CLASSES = [
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.a",
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.b",
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.KeymapUploadPanelView",
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.ConfirmCancelFloatingView",
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.ComponentSettingsViews.Macro.MacroOperationEditor",
    "com.zjx.jyandroid.ForegroundService.UI.UploadKeymapModule.ComponentSettingsViews.Macro.MacroOperationPositionEditorPanel",
    "com.zjx.jyandroid.ForegroundService.UI.SelectKeymapModule.SelectKeymapContainerView",
]
WIDGETS = [
    "com.zjx.jyandroid.base.Components.FilledSliderWithButtons",
    "com.zjx.jyandroid.base.Components.TextWithSliderView",
    "com.zjx.jyandroid.base.Components.TextWithSwitchView",
    "com.zjx.jyandroid.base.Components.TextViewComponent",
]
# keys drawn over the game must keep matching the game's buttons
EXCLUDE = {"components_holder_view", "empty"}
ACTIVITY_PREFIX = ("activity_", "main_page_view", "settings_page_view", "start_game_table_row",
                   "add_game_table_row")
ACTIVITY_PKG = ("com.zjx.jyandroid.MainApp.", "com.zjx.jyandroid.ADB.", "mdm.")

TEXT_SIMPLE = {"TextView", "Button", "EditText", "CheckBox", "RadioButton", "Switch",
               "ToggleButton", "CheckedTextView", "AutoCompleteTextView"}
TEXT_FQ_SUFFIX = ("AppCompatTextView", "AppCompatButton", "AppCompatEditText", "AppCompatCheckBox",
                  "MaterialButton", "MaterialTextView", "SwitchCompat", "SwitchMaterial",
                  "MaterialCheckBox", "TextInputEditText")

B = sys.argv[1]
RES = os.path.join(B, "res")
LAYOUT = os.path.join(RES, "layout")
UNIT_RE = re.compile(r"^(-?\d+(?:\.\d+)?)(dip|dp|sp)$")
TAG_RE = re.compile(r"<([A-Za-z_][A-Za-z0-9_.$]*)((?:\s+[^<>]*?)?)(/?)>", re.S)
ATTR_RE = re.compile(r'([A-Za-z_][\w.]*:[\w.]+)="([^"]*)"')


def rd(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def wr(p, s):
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


# ---------------------------------------------------------------- resources

def load_dimens(qual_dir):
    d = {}
    for p in glob.glob(os.path.join(RES, qual_dir, "*.xml")):
        for name, val in re.findall(r'<dimen name="([^"]+)">([^<]*)</dimen>', rd(p)):
            d[name] = val.strip()
    return d


DIMENS = load_dimens("values")
DIMENS.update(load_dimens("values-sw600dp-v13"))


def resolve_dimen(ref, depth=0):
    """'@dimen/x' -> '11.0sp' (or None if not a scalable unit)."""
    if depth > 8 or not ref.startswith("@dimen/"):
        return None
    v = DIMENS.get(ref[len("@dimen/"):])
    if v is None:
        return None
    if v.startswith("@dimen/"):
        return resolve_dimen(v, depth + 1)
    return v if UNIT_RE.match(v) else None


STYLES = {}
for _n, _parent, _body in re.findall(r'<style name="([^"]+)"(?: parent="([^"]*)")?\s*>(.*?)</style>',
                                     rd(os.path.join(RES, "values", "styles.xml")), re.S):
    STYLES[_n] = (_parent, _body)


def style_text_size(name, depth=0):
    """textSize defined by an app style (following parents); None if unknown."""
    if depth > 10 or name not in STYLES:
        return None
    parent, body = STYLES[name]
    m = re.search(r'<item name="android:textSize">([^<]+)</item>', body)
    if m:
        v = m.group(1).strip()
        return resolve_dimen(v) if v.startswith("@dimen/") else (v if UNIT_RE.match(v) else None)
    m = re.search(r'<item name="android:textAppearance">@style/([^<]+)</item>', body)
    if m:
        r = style_text_size(m.group(1).strip(), depth + 1)
        if r:
            return r
    if parent:
        return style_text_size(parent.replace("@style/", ""), depth + 1)
    if "." in name:
        return style_text_size(name.rsplit(".", 1)[0], depth + 1)
    return None


def scaled(v):
    m = UNIT_RE.match(v)
    num = float(m.group(1)) * SCALE
    unit = "dip" if m.group(2) in ("dip", "dp") else "sp"
    return "%s%s" % (("%.1f" % num), unit)


# ---------------------------------------------------------------- layout set

def smali_files_for(cls):
    rel = cls.replace(".", "/")
    out = []
    for d in glob.glob(os.path.join(B, "smali*")):
        out += glob.glob(os.path.join(d, rel + ".smali"))
        out += glob.glob(os.path.join(d, rel + "$*.smali"))
    return out


_cls_cache = {}


def layouts_of_class(cls):
    if cls not in _cls_cache:
        s = set()
        for p in smali_files_for(cls):
            s.update(re.findall(r"R\$layout;->(\w+):I", rd(p)))
        _cls_cache[cls] = s
    return _cls_cache[cls]


def classes_in(text):
    found = re.findall(r"<([a-z]\w*(?:\.[\w$]+)+)", text)
    return {c for c in found if c.rsplit(".", 1)[-1][:1].isupper()}


# mdm views that live in overlay menus (all other mdm.* views belong to the app's own pages)
OVERLAY_MDM = {"mdm.SensConvert"}


def is_activity_layout(name, text):
    if name.startswith(ACTIVITY_PREFIX):
        return True
    return any(c.startswith(ACTIVITY_PKG) and c not in OVERLAY_MDM for c in classes_in(text))


def allowed(name):
    p = os.path.join(LAYOUT, name + ".xml")
    return name not in EXCLUDE and os.path.exists(p) and not is_activity_layout(name, rd(p))


def layout_set():
    all_layouts = {os.path.basename(p)[:-4]: rd(p) for p in glob.glob(os.path.join(LAYOUT, "*.xml"))}
    users = {w: {n for n, t in all_layouts.items() if ("<" + w) in t} for w in WIDGETS}
    seeds = set(SEEDS)
    for c in SEED_CLASSES:
        seeds |= layouts_of_class(c)
    todo = [n for n in seeds if allowed(n)]
    done = set()
    while todo:
        n = todo.pop()
        if n in done:
            continue
        done.add(n)
        t = all_layouts[n]
        nxt = set(re.findall(r'layout="@layout/(\w+)"', t))
        for c in classes_in(t):
            nxt |= layouts_of_class(c)
            if c in users:
                nxt |= users[c]
        todo += [m for m in nxt if m not in done and allowed(m)]
    # every overlay layout that uses a scaled widget, so sibling tabs match
    for w in WIDGETS:
        for n in users[w]:
            if n not in done and allowed(n):
                todo.append(n)
    while todo:
        n = todo.pop()
        if n in done:
            continue
        done.add(n)
        t = all_layouts[n]
        nxt = set(re.findall(r'layout="@layout/(\w+)"', t))
        for c in classes_in(t):
            nxt |= layouts_of_class(c)
        todo += [m for m in nxt if m not in done and allowed(m)]
    return sorted(done)


# ---------------------------------------------------------------- scaling

def is_text_widget(tag):
    simple = tag.rsplit(".", 1)[-1]
    if "." not in tag:
        return simple in TEXT_SIMPLE
    return simple.endswith(TEXT_FQ_SUFFIX)


stats = {"values": 0, "dimens": 0, "added_text": 0, "unresolved": set()}


def scale_tag(m):
    tag, attrs, close = m.group(1), m.group(2) or "", m.group(3)

    def fix(am):
        k, v = am.group(1), am.group(2)
        if UNIT_RE.match(v):
            if float(UNIT_RE.match(v).group(1)) != 0:
                stats["values"] += 1
            return '%s="%s"' % (k, scaled(v))
        if v.startswith("@dimen/"):
            r = resolve_dimen(v)
            if r:
                stats["dimens"] += 1
                return '%s="%s"' % (k, scaled(r))
            stats["unresolved"].add(v)
        return am.group(0)

    attrs = ATTR_RE.sub(fix, attrs)
    if is_text_widget(tag) and "android:textSize=" not in attrs:
        base = None
        sm = re.search(r'style="@style/([^"]+)"', attrs)
        am = re.search(r'android:textAppearance="@style/([^"]+)"', attrs)
        if sm:
            base = style_text_size(sm.group(1))
        if base is None and am:
            base = style_text_size(am.group(1))
        if base is None and not (sm or am):
            base = "14.0sp"
        if base is not None:
            attrs = ' android:textSize="%s"' % scaled(base) + attrs
            stats["added_text"] += 1
    return "<%s%s%s>" % (tag, attrs, close)


def signature(text):
    """ids, tags and element order - must be identical between phone and tablet copies."""
    return (re.findall(r"<([A-Za-z_][\w.$]*)", text),
            re.findall(r'android:id="([^"]+)"', text),
            re.findall(r'android:tag="([^"]+)"', text))


def main():
    names = layout_set()
    if "--list" in sys.argv:
        print("\n".join(names))
        print("%d layouts" % len(names))
        return
    out = os.path.join(RES, OUT_DIR)
    os.makedirs(out, exist_ok=True)
    for p in glob.glob(os.path.join(out, "*.xml")):
        if MARK in rd(p):
            os.remove(p)
    for n in names:
        src = rd(os.path.join(LAYOUT, n + ".xml"))
        dst_path = os.path.join(out, n + ".xml")
        if os.path.exists(dst_path):
            sys.exit("refusing to overwrite hand-made %s" % dst_path)
        decl = ""
        body = src
        if body.startswith("<?xml"):
            decl, body = body.split("?>", 1)
            decl += "?>"
        body = TAG_RE.sub(scale_tag, body)
        new = decl + "\n" + MARK + body if decl else MARK + "\n" + body
        if signature(new) != signature(src):
            sys.exit("structure changed in %s" % n)
        wr(dst_path, new)
    print("scaled %d layouts x%.2f -> res/%s" % (len(names), SCALE, OUT_DIR))
    print("  %d literal values, %d @dimen resolved, %d text sizes added"
          % (stats["values"], stats["dimens"], stats["added_text"]))
    if stats["unresolved"]:
        print("  left as-is (not dp/sp): " + ", ".join(sorted(stats["unresolved"])))


main()
